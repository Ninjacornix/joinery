"""A typed library of game sounds, each a native patch of a real tool.

`make_sound` (joinery-sound) turns one `SoundSpec` into a source the owning tool
renders offline: a SuperCollider NRT patch (`.scd`) for everything noisy
(footsteps, hits, doors, ambience beds), seeded with `RandSeed` so a replay is
byte for byte the same, or a Surge XT JSON patch for the tonal ones (pickups,
UI blips), which use Surge's sine oscillator and no noise source. The patch is
plain text written from the spec here; nothing is generated by a model and no
sample is read.

A spec's `variant` picks another take of the same sound: the seed and small
pitch and filter offsets change, the character stays. Every number written into
a patch has fixed decimals, so the same spec always gives the same text.
"""

from __future__ import annotations

import hashlib
import json
import random
import re
from pathlib import PurePosixPath
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

Tool = Literal["supercollider", "surge-xt"]
SURFACES = ("default", "grass", "stone", "wood", "metal", "sand", "water")
#: One-shot sounds: kind -> (what it is, the tool that makes it).
EFFECTS: dict[str, tuple[str, Tool]] = {
    "footstep": ("A footstep on a surface", "supercollider"),
    "jump": ("A jump: a short push and a whoosh", "supercollider"),
    "land": ("A landing thump", "supercollider"),
    "pickup": ("A bright two-note pickup chime", "surge-xt"),
    "hit": ("A punchy hit", "supercollider"),
    "damage": ("Taking damage: a hit with a falling tone", "supercollider"),
    "ui_click": ("A short UI click", "surge-xt"),
    "ui_hover": ("A soft UI hover blip", "surge-xt"),
    "door": ("A door creaking open and shutting", "supercollider"),
    "button": ("A button press and release", "supercollider"),
    "lever": ("A lever ratchet and clunk", "supercollider"),
    "plate": ("A heavy pressure plate sinking", "supercollider"),
}
#: Looping beds, rendered to Ogg Vorbis with their loop points.
AMBIENCES: dict[str, str] = {
    "wind": "Outdoor wind, gusting slowly",
    "room_tone": "A quiet interior room tone",
    "cave": "A cave: low rumble and distant drips",
    "forest": "A forest bed: leaves and the odd chirp",
}
KINDS: tuple[str, ...] = (*EFFECTS, *AMBIENCES)
#: Loudness when the art bible sets none for the export's folder (LUFS).
DEFAULT_LUFS: dict[str, float] = {
    "footstep": -24.0,
    "jump": -22.0,
    "land": -22.0,
    "pickup": -18.0,
    "hit": -18.0,
    "damage": -18.0,
    "ui_click": -24.0,
    "ui_hover": -28.0,
    "door": -20.0,
    "button": -22.0,
    "lever": -20.0,
    "plate": -20.0,
    **dict.fromkeys(AMBIENCES, -22.0),
}
#: An ambience loop's length and the extra rendered for its crossfade (seconds).
LOOP_SECONDS = 12.0
CROSSFADE_SECONDS = 2.0
_NAME = re.compile(r"^[a-z0-9]+(_[a-z0-9]+)*$")


class SoundSpec(BaseModel):
    """One sound to make: what it is, which take, and where it goes."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    kind: Literal[
        "footstep",
        "jump",
        "land",
        "pickup",
        "hit",
        "damage",
        "ui_click",
        "ui_hover",
        "door",
        "button",
        "lever",
        "plate",
        "wind",
        "room_tone",
        "cave",
        "forest",
    ]
    #: File stem: step_grass -> audio/sfx/step_grass.wav.
    name: str = Field(min_length=1, max_length=64)
    #: Footsteps only: what the foot lands on.
    surface: (
        Literal["default", "grass", "stone", "wood", "metal", "sand", "water"] | None
    ) = None
    variant: int = Field(default=0, ge=0, le=99)
    #: The patch's random seed; derived from the rest when not given.
    seed: int | None = Field(default=None, ge=0, lt=2**31)

    @model_validator(mode="after")
    def consistent(self) -> SoundSpec:
        if not _NAME.match(self.name):
            raise ValueError(
                "name is lower_snake_case letters and digits, such as step_grass"
            )
        if self.kind == "footstep" and self.surface is None:
            raise ValueError("a footstep needs its surface: " + ", ".join(SURFACES))
        if self.kind != "footstep" and self.surface is not None:
            raise ValueError("only footsteps take a surface")
        return self

    # --- Where things go ---------------------------------------------------------

    @property
    def ambience(self) -> bool:
        return self.kind in AMBIENCES

    @property
    def tool(self) -> Tool:
        return "supercollider" if self.ambience else EFFECTS[self.kind][1]

    @property
    def folder(self) -> str:
        return "ambience" if self.ambience else "sfx"

    def source_path(self) -> str:
        suffix = ".scd" if self.tool == "supercollider" else ".json"
        return f"audio/sources/{self.folder}/{self.name}{suffix}"

    def export_path(self) -> str:
        if self.ambience:
            return f"audio/ambience/{self.name}.ogg"
        return f"audio/sfx/{self.name}.wav"

    def render_path(self, export: str) -> str:
        """Where the tool writes its raw render: the export itself for a WAV."""
        if PurePosixPath(export).suffix == ".wav":
            return export
        return f"audio/sources/{self.folder}/{self.name}.wav"

    @property
    def channels(self) -> int:
        """Ambience is stereo; one-shots are mono, so Godot places them in 3D."""
        return 2 if self.ambience else 1

    @property
    def default_lufs(self) -> float:
        return DEFAULT_LUFS[self.kind]

    @property
    def effective_seed(self) -> int:
        if self.seed is not None:
            return self.seed
        key = f"{self.kind}:{self.surface or ''}:{self.name}:{self.variant}"
        return int.from_bytes(hashlib.sha256(key.encode()).digest()[:4], "big") >> 1

    def describe(self) -> str:
        if self.ambience:
            return AMBIENCES[self.kind]
        words = EFFECTS[self.kind][0]
        if self.surface:
            words = f"A footstep on {self.surface}"
        return words + (f" (take {self.variant + 1})" if self.variant else "")

    # --- The recipe --------------------------------------------------------------

    def steps(self) -> list[dict[str, Any]]:
        """Audio edits after the render: loop points for a bed, then loudness."""
        steps: list[dict[str, Any]] = []
        if self.ambience:
            steps.append(
                {
                    "op": "loop",
                    "start": 0.0,
                    "end": LOOP_SECONDS,
                    "crossfade": CROSSFADE_SECONDS,
                }
            )
        steps.append({"op": "normalise"})
        return steps

    def source_text(self, render: str, sample_rate: int, channels: int) -> str:
        """The native patch: SuperCollider code or a Surge XT JSON source."""
        rng = random.Random(self.effective_seed)
        if self.tool == "surge-xt":
            return _surge(self, rng, sample_rate)
        return _supercollider(self, rng, render, sample_rate, channels)


def spec_for(arguments: dict[str, Any]) -> SoundSpec:
    """A make_sound call's spec (unknown keys are left to the caller)."""
    fields = {k: arguments[k] for k in SoundSpec.model_fields if k in arguments}
    return SoundSpec.model_validate(fields)


def app_for(arguments: dict[str, Any]) -> str:
    """The app a make_sound call runs, for worker slots; "" when it can't be told."""
    kind = str(arguments.get("kind", ""))
    if kind in AMBIENCES:
        return "supercollider"
    if kind in EFFECTS:
        return EFFECTS[kind][1]
    return ""


# --- SuperCollider ------------------------------------------------------------------


def _n(value: float) -> str:
    return f"{value:.4f}"


def _j(rng: random.Random, value: float, amount: float = 0.06) -> str:
    """`value` nudged by up to ±amount, so each take differs a little."""
    return _n(value * (1.0 + rng.uniform(-amount, amount)))


def _step_body(surface: str, rng: random.Random) -> tuple[str, float]:
    """A footstep: heel then toe, shaped by what the foot lands on."""
    toe = 0.055 + rng.uniform(0.0, 0.03)
    env = (
        f"env = EnvGen.ar(Env.new([0, 1, 0.04, 0.65, 0], "
        f"[0.002, {_n(toe)}, 0.002, {{tail}}], [0, -7, 0, -7]));\n"
    )
    bodies = {
        "default": (
            0.09,
            (
                "sig = BPF.ar(WhiteNoise.ar * env, {f1}, 1.1) * 2.5"
                " + (SinOsc.ar(XLine.ar({f2}, 60, 0.08)) * EnvGen.ar(Env.perc(0.001, 0.08)) * 0.5);\n"
            ),
            (900, 140),
        ),
        "grass": (
            0.16,
            (
                "sig = HPF.ar(WhiteNoise.ar * Decay.ar(Dust.ar(420), 0.004) * env, {f1})"
                " * 3 + (BPF.ar(WhiteNoise.ar * env, {f2}, 1.5) * 0.8);\n"
            ),
            (1800, 3600),
        ),
        "stone": (
            0.045,
            (
                "sig = (BPF.ar(WhiteNoise.ar * env, {f1}, 0.7) * 2.2)"
                " + (BPF.ar(WhiteNoise.ar * env, {f2}, 1) * 0.9);\n"
            ),
            (2400, 650),
        ),
        "wood": (
            0.07,
            (
                "sig = Klank.ar(`[[{f1}, {f1} * 2.17, {f1} * 4.6, {f1} * 7.7],"
                " [1, 0.6, 0.35, 0.2], [0.09, 0.06, 0.04, 0.03]], WhiteNoise.ar * env * 0.06)"
                " + (BPF.ar(WhiteNoise.ar * env, {f2}, 1) * 0.6);\n"
            ),
            (190, 1200),
        ),
        "metal": (
            0.05,
            (
                "sig = Klank.ar(`[[{f1}, {f1} * 2.27, {f1} * 3.52, {f1} * 5.18, {f1} * 6.73],"
                " [1, 0.7, 0.5, 0.35, 0.2], [0.35, 0.3, 0.22, 0.16, 0.1]], WhiteNoise.ar * env * 0.03)"
                " + (BPF.ar(WhiteNoise.ar * env, {f2}, 0.8) * 0.5);\n"
            ),
            (520, 3000),
        ),
        "sand": (
            0.2,
            (
                "sig = (LPF.ar(WhiteNoise.ar * Decay.ar(Dust.ar(1100), 0.003), {f1}) * env * 3)"
                " + (LPF.ar(WhiteNoise.ar * env, {f2}) * 0.5);\n"
            ),
            (1800, 700),
        ),
        "water": (
            0.18,
            (
                "sig = (BPF.ar(WhiteNoise.ar * env, XLine.ar({f1}, {f1} * 3, 0.15), 0.6) * 2)"
                " + (SinOsc.ar(XLine.ar({f2}, {f2} * 2.3, 0.08)) * EnvGen.ar(Env.perc(0.01, 0.09)) * 0.25)"
                " + (BPF.ar(WhiteNoise.ar * Decay.ar(Dust.ar(300), 0.01), 1800, 1) * env * 0.6);\n"
            ),
            (520, 650),
        ),
    }
    tail, line, (f1, f2) = bodies[surface]
    code = env.format(tail=_j(rng, tail, 0.1)) + line.format(
        f1=_j(rng, f1), f2=_j(rng, f2)
    )
    return code, 0.5


def _effect_body(kind: str, rng: random.Random) -> tuple[str, float]:
    """Code that sets `sig` (mono) for a one-shot, and the seconds it lasts."""
    lines: dict[str, tuple[str, float]] = {
        "jump": (
            (
                "sig = (BPF.ar(WhiteNoise.ar, XLine.ar({a}, {b}, 0.2), 0.5)"
                " * EnvGen.ar(Env.perc(0.02, 0.22)) * 1.5)"
                " + (SinOsc.ar(XLine.ar({c}, {c} * 1.6, 0.08)) * EnvGen.ar(Env.perc(0.001, 0.08)) * 0.4);\n"
            ),
            0.5,
        ),
        "land": (
            (
                "sig = (SinOsc.ar(XLine.ar({a}, 42, 0.16)) * EnvGen.ar(Env.perc(0.001, 0.22)))"
                " + (LPF.ar(WhiteNoise.ar, {b}) * EnvGen.ar(Env.perc(0.001, 0.12)) * 0.7);\n"
            ),
            0.5,
        ),
        "hit": (
            (
                "sig = (SinOsc.ar(XLine.ar({a}, 55, 0.12)) * EnvGen.ar(Env.perc(0.001, 0.18)))"
                " + (BPF.ar(WhiteNoise.ar, {b}, 1) * EnvGen.ar(Env.perc(0.001, 0.06)) * 1.5);\n"
                "sig = (sig * 3).tanh * 0.5;\n"
            ),
            0.5,
        ),
        "damage": (
            (
                "sig = (SinOsc.ar(XLine.ar({a}, 55, 0.12)) * EnvGen.ar(Env.perc(0.001, 0.16)))"
                " + (BPF.ar(WhiteNoise.ar, {b}, 1) * EnvGen.ar(Env.perc(0.001, 0.05)) * 1.2)"
                " + (LPF.ar(Saw.ar(XLine.ar({c} * 3, {c}, 0.3)), 1800) * EnvGen.ar(Env.perc(0.01, 0.32)) * 0.3);\n"
                "sig = (sig * 2.5).tanh * 0.5;\n"
            ),
            0.6,
        ),
        "door": (
            (
                "sig = BPF.ar(Saw.ar({c} * 0.45 + LFNoise1.kr(9).range(-10, 10)), [{b} * 0.5, {b}], 0.15).sum"
                " * EnvGen.ar(Env.linen(0.05, 0.55, 0.2)) * 1.4;\n"
                "sig = sig + (SinOsc.ar(XLine.ar({a} * 0.6, 38, 0.25))"
                " * EnvGen.ar(Env.new([0, 0, 1, 0], [0.85, 0.001, 0.3], [0, 0, -5])));\n"
                "sig = sig + (LPF.ar(WhiteNoise.ar, 700)"
                " * EnvGen.ar(Env.new([0, 0, 0.6, 0], [0.85, 0.001, 0.12], [0, 0, -6])));\n"
            ),
            1.4,
        ),
        "button": (
            (
                "sig = Klank.ar(`[[{b}, {b} * 1.48], [1, 0.5], [0.03, 0.02]],"
                " (Impulse.ar(0) + DelayN.ar(Impulse.ar(0), 0.2, 0.09) * 0.6) * 0.5)"
                " + (BPF.ar(WhiteNoise.ar * EnvGen.ar(Env.perc(0.0005, 0.012)), 3600, 0.5) * 2)"
                " + (SinOsc.ar(XLine.ar({a} * 1.5, 110, 0.08)) * EnvGen.ar(Env.perc(0.001, 0.14)) * 0.7)"
                " + (LPF.ar(WhiteNoise.ar, 1200) * EnvGen.ar(Env.new([0, 0, 0.5, 0], [0.09, 0.001, 0.1], [0, 0, -5])));\n"
            ),
            0.5,
        ),
        "lever": (
            (
                "sig = Klank.ar(`[[{b}, {b} * 1.9, {b} * 3.2], [1, 0.5, 0.3], [0.03, 0.02, 0.015]],"
                " Impulse.ar(Line.kr(32, 18, 0.26)) * EnvGen.ar(Env.new([0, 1, 1, 0], [0, 0.26, 0])) * 0.3);\n"
                "sig = sig + (SinOsc.ar(XLine.ar({a}, 60, 0.12))"
                " * EnvGen.ar(Env.new([0, 0, 1, 0], [0.3, 0.001, 0.18], [0, 0, -5])));\n"
            ),
            0.6,
        ),
        "plate": (
            (
                "sig = (SinOsc.ar(XLine.ar({a} * 0.6, 45, 0.2)) * EnvGen.ar(Env.perc(0.002, 0.25)))"
                " + (LPF.ar(BrownNoise.ar, {b} * 0.4) * EnvGen.ar(Env.new([0, 0.6, 0], [0.04, 0.3])))"
                " + (BPF.ar(WhiteNoise.ar, 1600, 1) * EnvGen.ar(Env.perc(0.001, 0.03)) * 0.5);\n"
            ),
            0.6,
        ),
    }
    line, seconds = lines[kind]
    return (
        line.format(a=_j(rng, 160), b=_j(rng, 1500), c=_j(rng, 140)),
        seconds,
    )


def _ambience_body(kind: str, rng: random.Random) -> str:
    """Code that sets a stereo `sig` for a looping bed."""
    lines = {
        "wind": (
            "sig = BPF.ar(WhiteNoise.ar(0.6 ! 2), LFNoise1.kr([{a}, {b}]).exprange(260, 1400), 0.35)"
            " + (LPF.ar(PinkNoise.ar(0.25 ! 2), 320) * LFNoise1.kr(0.07 ! 2).range(0.4, 1));\n"
        ),
        "room_tone": (
            "sig = LPF.ar(BrownNoise.ar(0.35 ! 2), 230) + SinOsc.ar([60, 60.3], 0, 0.012)"
            " + HPF.ar(PinkNoise.ar(0.012 ! 2), 3000);\n"
        ),
        "cave": (
            "sig = LPF.ar(BrownNoise.ar(0.3 ! 2), 170)"
            " + (Ringz.ar(Dust.ar([{a}, {b}] * 4), LFNoise0.kr(0.7 ! 2).range(900, 2600), 0.09) * 0.12);\n"
            "sig = FreeVerb.ar(sig, 0.4, 0.9, 0.3);\n"
        ),
        "forest": (
            "sig = BPF.ar(PinkNoise.ar(0.5 ! 2), 2300, 1.6) * LFNoise1.kr([{a}, {b}] * 2).range(0.25, 0.8);\n"
            "sig = sig + (SinOsc.ar(Decay.ar(Dust.ar(0.35 ! 2), 0.05) * 1400 + 2800)"
            " * Decay.ar(Dust.ar(0.35 ! 2), 0.08) * 0.04);\n"
        ),
    }
    return lines[kind].format(a=_j(rng, 0.13, 0.2), b=_j(rng, 0.17, 0.2))


def _supercollider(
    spec: SoundSpec,
    rng: random.Random,
    render: str,
    sample_rate: int,
    channels: int,
) -> str:
    seed = spec.effective_seed
    if spec.ambience:
        body = _ambience_body(spec.kind, rng)
        seconds = LOOP_SECONDS + CROSSFADE_SECONDS
    elif spec.kind == "footstep":
        assert spec.surface is not None
        body, seconds = _step_body(spec.surface, rng)
    else:
        body, seconds = _effect_body(spec.kind, rng)
    if not spec.ambience:
        # Tame the crest factor: a one-shot then reaches its loudness target
        # without its true peak passing the ceiling.
        body += "sig = Compander.ar(sig, sig, 0.2, 1, 0.33, 0.002, 0.08);\n"
        body += "sig = LPF.ar(sig, 12000);\n"
    if channels == 2 and not spec.ambience:
        body += "sig = sig ! 2;\n"
    if channels == 1 and spec.ambience:
        body += "sig = sig.sum * 0.7;\n"
    definition = f"joinery_{spec.kind}"
    describe = spec.describe().replace('"', "'")
    return (
        f"// Joinery sound kit: {describe}.\n"
        f"// kind={spec.kind} surface={spec.surface or '-'} variant={spec.variant} seed={seed}\n"
        "(\n"
        f"var definition = SynthDef(\\{definition}, {{ |out = 0|\n"
        "    var sig, env;\n"
        f"    RandSeed.ir(1, {seed});\n"
        + "".join("    " + line + "\n" for line in body.strip().splitlines())
        + "    Out.ar(out, Limiter.ar(LeakDC.ar(sig) * 0.5, 0.95, 0.002));\n"
        "});\n"
        "var score = Score([\n"
        "    [0.0, [\\d_recv, definition.asBytes]],\n"
        f"    [0.0, [\\s_new, \\{definition}, 1000, 0, 0]],\n"
        f"    [{_n(seconds)}, [\\c_set, 0, 0]]\n"
        "]);\n"
        f'score.recordNRT(outputFilePath: "{render}", sampleRate: {sample_rate},\n'
        '    headerFormat: "WAV", sampleFormat: "int16",\n'
        f"    options: ServerOptions.new.numOutputBusChannels_({channels}),\n"
        f"    duration: {_n(seconds)}, action: {{ 0.exit }});\n"
        ")\n"
    )


# --- Surge XT -----------------------------------------------------------------------


def _surge(spec: SoundSpec, rng: random.Random, sample_rate: int) -> str:
    """A sine patch with a plucked envelope; notes per kind."""
    shift = (spec.variant * 2) % 7
    decay = {"pickup": 180.0, "ui_click": 22.0, "ui_hover": 45.0}[spec.kind]
    attack = {"pickup": 1.0, "ui_click": 0.5, "ui_hover": 4.0}[spec.kind]
    if spec.kind == "pickup":
        notes = [
            {"pitch": 76 + shift, "start": 0.0, "duration": 0.09, "velocity": 112},
            {"pitch": 83 + shift, "start": 0.08, "duration": 0.16, "velocity": 120},
        ]
    elif spec.kind == "ui_click":
        notes = [{"pitch": 96 + shift, "start": 0.0, "duration": 0.03, "velocity": 110}]
    else:
        notes = [{"pitch": 88 + shift, "start": 0.0, "duration": 0.06, "velocity": 90}]
    patch = {
        "synth": "surge-xt",
        "sample_rate": sample_rate,
        "seconds": 0.5 if spec.kind != "pickup" else 0.6,
        "parameters": {
            "a_osc_1_type": "Sine",
            "a_amp_eg_attack": round(attack * (1 + rng.uniform(-0.05, 0.05)), 3),
            "a_amp_eg_decay": round(decay * (1 + rng.uniform(-0.08, 0.08)), 3),
            "a_amp_eg_sustain": 0.0,
            "a_amp_eg_release": round(decay * 0.5, 3),
        },
        "notes": notes,
    }
    return json.dumps(patch, indent=2) + "\n"
