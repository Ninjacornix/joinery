"""Bring a staged change up to date with changes the user accepted while it was made.

With several tasks at once (ADR 0036) the project can move under a staged change:
another task's change is accepted first. Files this change didn't touch simply
follow the project. ``joinery.lock`` is merged entry by entry, since every change
that makes an asset adds its own entry. A folder both changes created is the same
folder. Anything else changed on both sides is a conflict: the task is asked to
redo that file on top of the accepted version, never silently merged.
"""

from __future__ import annotations

import json
import shutil
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from joinery.transactions import DIRECTORY, FileTransaction, copy_file, inventory

LOCK = "joinery.lock"
LOCK_HEAD = (
    "# Generated by `joinery lock`. Every asset under art/ and audio/ needs\n"
    "# an entry: a tool that made it and a recipe that remakes it, or an\n"
    "# import the user declared. Hashes are measured, never written by hand.\n"
    "version = 1\n"
)


@dataclass
class Rebase:
    #: Files brought in from the project because this change didn't touch them.
    refreshed: list[str] = field(default_factory=list)
    #: Files merged (the lock).
    merged: list[str] = field(default_factory=list)
    #: Files changed both here and in the project.
    conflicts: list[str] = field(default_factory=list)


def _block(name: str, entry: dict[str, Any]) -> str:
    lines = [f"[[{name}]]"]
    lines += [f"{key} = {json.dumps(value)}" for key, value in entry.items()]
    return "\n".join(lines) + "\n"


def merge_lock(theirs: str, mine: str, touched: set[str]) -> str:
    """The project's lock (``theirs``) with this change's own entries (``mine``).

    ``touched`` are the paths this change created, changed or deleted: their
    entries come from ``mine``; every other entry stays as the project has it.
    Raises ValueError when either lock can't be read.
    """
    ours, project = tomllib.loads(mine), tomllib.loads(theirs)
    assets: dict[str, dict[str, Any]] = {
        str(e.get("path", "")): e for e in project.get("asset", [])
    }
    mine_assets = {str(e.get("path", "")): e for e in ours.get("asset", [])}
    for path, entry in mine_assets.items():
        if path not in assets or path in touched:
            assets[path] = entry
    for path in [p for p in assets if p in touched and p not in mine_assets]:
        del assets[path]
    extensions = {str(e.get("name", "")): e for e in project.get("extensions", [])}
    for entry in ours.get("extensions", []):
        extensions.setdefault(str(entry.get("name", "")), entry)
    text = LOCK_HEAD
    for path in sorted(assets):
        text += "\n" + _block("asset", assets[path])
    for name in sorted(extensions):
        text += "\n" + _block("extensions", extensions[name])
    tomllib.loads(text)  # never stage a lock that doesn't read back
    return text


def _take(tx: FileTransaction, path: str, value: str) -> bool:
    """Make the stage's ``path`` what the project has (``value``); False if it can't."""
    target = tx.stage / path
    try:
        if value == DIRECTORY:
            if target.exists() and not target.is_dir():
                target.unlink()
            target.mkdir(parents=True, exist_ok=True)
        elif value:
            if target.is_dir():
                shutil.rmtree(target)
            target.parent.mkdir(parents=True, exist_ok=True)
            copy_file(tx.project / path, target)
        elif target.is_dir():
            target.rmdir()
        else:
            target.unlink(missing_ok=True)
    except OSError:
        return False
    return True


def _order(item: tuple[str, str, str]) -> tuple[int, int]:
    path, before, now = item
    depth = len(Path(path).parts)
    if now == DIRECTORY:
        return (0, depth)  # make folders before their files
    if before == DIRECTORY:
        return (2, -depth)  # remove folders after their files, deepest first
    return (1, depth)


def rebase(tx: FileTransaction, *, take_theirs: bool) -> Rebase:
    """Follow the project in ``tx``'s stage (a change still staging).

    With ``take_theirs`` a conflicting file is replaced by the project's version,
    so the agent redoes its part on top of it; otherwise it is left for the submit.
    """
    result = Rebase()
    if tx.state != "staging":
        return result
    current = inventory(tx.project, include_dirs=tx.include_dirs)
    staged = inventory(tx.stage, include_dirs=tx.include_dirs)
    base = tx.base
    moved = [
        (path, base.get(path, ""), current.get(path, ""))
        for path in sorted(base.keys() | current.keys())
        if base.get(path, "") != current.get(path, "")
    ]
    if not moved:
        return result
    touched = {
        path
        for path in base.keys() | staged.keys()
        if base.get(path, "") != staged.get(path, "")
    }
    for path, before, now in sorted(moved, key=_order):
        mine = staged.get(path, "")
        if path not in touched:
            if _take(tx, path, now):
                result.refreshed.append(path)
                _settle(base, path, now)
            else:
                result.conflicts.append(path)
        elif mine == now:
            _settle(base, path, now)
        elif path == LOCK and mine and now and DIRECTORY not in {mine, now}:
            try:
                merged = merge_lock(
                    (tx.project / LOCK).read_text(encoding="utf-8"),
                    (tx.stage / LOCK).read_text(encoding="utf-8"),
                    touched,
                )
            except (OSError, ValueError):
                result.conflicts.append(path)
                continue
            (tx.stage / LOCK).write_text(merged, encoding="utf-8")
            _settle(base, path, now)
            result.merged.append(path)
        else:
            result.conflicts.append(path)
            if take_theirs and _take(tx, path, now):
                _settle(base, path, now)
    tx._record()
    return result


def _settle(base: dict[str, str], path: str, now: str) -> None:
    if now:
        base[path] = now
    else:
        base.pop(path, None)


def refresh_review(tx: FileTransaction) -> list[str]:
    """Let a change in review be accepted after another change moved the project.

    Only the lock and folders are brought up to date (the files the user saw stay
    exactly as reviewed). Returns the files that still conflict; the accept then
    refuses them as before.
    """
    if tx.state != "review":
        return []
    current = inventory(tx.project, include_dirs=tx.include_dirs)
    moved = [c for c in tx.changes if current.get(c["path"], "") != c["before"]]
    if not moved:
        return []
    touched = {c["path"] for c in tx.changes}
    left: list[str] = []
    lock: str | None = None
    for change in moved:
        path, now = change["path"], current.get(change["path"], "")
        if now == change["after"]:
            continue
        if path == LOCK and change["after"] and now and DIRECTORY not in {now}:
            try:
                lock = merge_lock(
                    (tx.project / LOCK).read_text(encoding="utf-8"),
                    (tx.stage / LOCK).read_text(encoding="utf-8"),
                    touched,
                )
            except (OSError, ValueError):
                left.append(path)
            continue
        left.append(path)
    if left:
        return left
    if lock is not None:
        (tx.stage / LOCK).write_text(lock, encoding="utf-8")
    for change in moved:
        _settle(tx.base, change["path"], current.get(change["path"], ""))
    changes = tx.diff()
    tx._capture(changes)
    tx._record(changes=changes)
    return []
