"""Write each supported agent's hook config so the Joinery gate fires in it.

Every file produced here runs the same command, `joinery hook`, through the
agent's own hook mechanism. `project.py` calls `write_agent_wiring` for all
agents when scaffolding a project; the repo itself carries the same files for
whichever agents work on the engine. Fail-closed: an agent whose blocking hook
Joinery cannot rely on is not wired silently (see `unwireable`).

Two directories matter and are not the same:

* the *engine* dir, where `joinery` is installed — passed to `uv run --project`
  so the command resolves. It is baked in per install.
* the *project* dir, whose `joinery.toml` lists the enabled tools — the hook
  resolves this itself at call time (agent env var, stdin cwd, then git root),
  so nothing here has to hard-code it.

For the engine repo's own config, the engine dir is written portably as the
agent's project-dir variable where one exists, so the committed files work on
any clone. Scaffolded game projects point at the concrete engine install.
"""

from __future__ import annotations

import json
import shlex
from pathlib import Path

from joinery.agents import Agent, all_agents
from joinery.catalog import ROOT

# The command every agent runs. `uv run --project <engine>` keeps it on
# Joinery's pinned env. `{engine}` is an explicit engine dir; the empty string
# drops `--project` so uv discovers the env from the working directory (used for
# the engine repo's own config under agents that run hooks in the repo cwd).
# `--agent <id>` tells the hook how to signal a Rule Zero stop in that agent.
_HOOK_HEAD = ["run", "--frozen", "--quiet"]
_HOOK_FOOT = ["joinery", "hook"]
_MATCHER_CLAUDE = "mcp__.*|Bash|WebFetch"
_MATCHER_CODEX = "mcp__.*|Bash"
_MATCHER_GEMINI = "mcp_.*|run_shell_command|web_fetch"
_TELEMETRY_OFF = {"DISABLE_TELEMETRY": "1", "DISABLE_ERROR_REPORTING": "1"}


def _args(engine: str, agent_id: str = "") -> list[str]:
    project = ["--project", engine] if engine else []
    agent = ["--agent", agent_id] if agent_id else []
    return [*_HOOK_HEAD, *project, *_HOOK_FOOT, *agent]


def _command_str(engine: str, agent_id: str = "") -> str:
    return " ".join(
        '"${CLAUDE_PROJECT_DIR}"'
        if part == "${CLAUDE_PROJECT_DIR}"
        else shlex.quote(part)
        for part in ["uv", *_args(engine, agent_id)]
    )


def unwireable(agents: tuple[Agent, ...] = all_agents()) -> list[str]:
    """Agents Joinery refuses to rely on because they have no blocking gate."""
    return [a.id for a in agents if not a.blocking_hook]


def _claude_settings(engine: str) -> dict[str, object]:
    hook = {
        "type": "command",
        "command": _command_str(engine, "claude"),
        "timeout": 30,
    }
    return {
        "enableAllProjectMcpServers": False,
        "env": _TELEMETRY_OFF,
        "hooks": {"PreToolUse": [{"matcher": _MATCHER_CLAUDE, "hooks": [hook]}]},
    }


def _codex_hooks(engine: str) -> dict[str, object]:
    # Codex runs hooks in the session cwd and has no guaranteed project-dir env,
    # so the command resolves the dir itself (git root). Errors fail-closed in
    # the hook; Codex itself does not block on hook error, a documented limit.
    hook = {
        "type": "command",
        "command": _command_str(engine, "codex"),
        "timeout": 30,
        "statusMessage": "Joinery policy check",
    }
    return {
        "description": "Joinery creation-only gate (Rule Zero).",
        "hooks": {"PreToolUse": [{"matcher": _MATCHER_CODEX, "hooks": [hook]}]},
    }


def _gemini_settings(engine: str) -> dict[str, object]:
    # Gemini fires BeforeTool, names MCP tools mcp_<server>_<tool>, and provides
    # cwd on stdin; the hook reads all three. Timeout is milliseconds here.
    hook = {
        "type": "command",
        "command": _command_str(engine, "gemini"),
        "name": "joinery-gate",
        "timeout": 30000,
        "description": "Joinery creation-only gate (Rule Zero).",
    }
    return {
        "telemetry": {"enabled": False},
        "hooks": {"BeforeTool": [{"matcher": _MATCHER_GEMINI, "hooks": [hook]}]},
    }


def _opencode_plugin(engine: str) -> str:
    # opencode hooks are an in-process JS plugin: tool.execute.before runs the
    # same `joinery hook`, feeding it a canonical payload, and throws to block.
    # Nothing is disabled to compensate for the subagent gap (#5894); the
    # sandbox and the CI asset gate cover that path.
    cmd = json.dumps(["uv", *_args(engine, "opencode")])
    return (
        "// Generated by Joinery. Enforces the creation-only gate (Rule Zero).\n"
        "// Runs `joinery hook` before every tool call and blocks on a non-zero exit.\n"
        "import { spawnSync } from 'node:child_process'\n\n"
        "export const JoineryGate = async () => ({\n"
        "  'tool.execute.before': async (input, output) => {\n"
        "    const payload = JSON.stringify({\n"
        "      tool: input.tool,\n"
        "      server: input.server ?? '',\n"
        "      args: output?.args ?? {},\n"
        "      directory: input.directory ?? process.cwd(),\n"
        "    })\n"
        f"    const argv = {cmd}\n"
        "    const res = spawnSync(argv[0], argv.slice(1), { input: payload, encoding: 'utf8' })\n"
        "    if (res.status !== 0) {\n"
        "      throw new Error(res.stderr?.trim() || 'Blocked by Joinery policy')\n"
        "    }\n"
        "  },\n"
        "})\n"
    )


# No tool is disabled or removed anywhere in these configs. Every tool stays
# callable and is judged per call by the hook, which stops the turn on a Rule
# Zero violation and denies a single call when something is merely not enabled.


def _content(agent: Agent, engine: str) -> str:
    if agent.id == "claude":
        return json.dumps(_claude_settings(engine), indent=2) + "\n"
    if agent.id == "codex":
        return json.dumps(_codex_hooks(engine), indent=2) + "\n"
    if agent.id == "gemini":
        return json.dumps(_gemini_settings(engine), indent=2) + "\n"
    if agent.id == "opencode":
        return _opencode_plugin(engine)
    raise KeyError(f"no wiring for agent {agent.id!r}")


def _engine_ref(agent: Agent, portable: bool) -> str:
    """The engine dir to bake into the command.

    Scaffolded projects always get the concrete engine install path, since a
    game project lives elsewhere and must still find `joinery`. The engine
    repo's own config is portable instead: it uses the agent's project-dir
    variable where one exists, and otherwise an empty string, which drops
    `--project` so uv discovers the env from the repo working directory. Either
    way a clone works without a machine-specific path committed to the repo.
    """
    if not portable:
        return str(ROOT)
    if agent.project_dir_env:
        return "${" + agent.project_dir_env + "}"
    return ""


def write_agent_wiring(
    root: Path,
    agents: tuple[Agent, ...] = all_agents(),
    *,
    portable: bool = False,
) -> list[str]:
    """Write every wireable agent's hook config under `root`. Returns the paths.

    Fail-closed: an agent without a reliable blocking hook is skipped, not
    silently half-wired. Callers that need the gate everywhere check
    `unwireable()` first. Pass `portable=True` for the engine repo's own config.
    """
    written: list[str] = []
    for agent in agents:
        if not agent.blocking_hook:
            continue
        path = root / agent.config_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_content(agent, _engine_ref(agent, portable)))
        written.append(agent.config_path)
    return written
