"""Write joinery.lock from what the recipes actually produced.

The asset gate needs an entry per file under art/ and audio/, carrying its
sha256 and where it came from. Maintaining those hashes by hand is the same
mistake as hand-writing the sandbox checksums: a wrong hash would look verified
while verifying nothing, and a stale one blocks the build for no reason.

So the entries are derived. Every recipe declares its outputs, which gives an
output -> (tool, recipe) map; each asset file is matched against it and recorded
as `tool-created` with its measured hash. A file under art/ or audio/ that no
recipe claims is reported rather than guessed at: it is either a human import,
which only the user may declare, or an asset nothing can rebuild, and both
need a person to decide.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from joinery.lockfile import LOCK_NAME, asset_files
from joinery.recipe import load_recipe, recipe_paths


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def claimed_outputs(project: Path) -> dict[str, tuple[str, str]]:
    """Map each recipe output to the tool that makes it and its recipe path."""
    claims: dict[str, tuple[str, str]] = {}
    for path in recipe_paths(project):
        recipe = load_recipe(path)
        rel_recipe = path.relative_to(project).as_posix()
        for out in recipe.outputs:
            claims[out] = (recipe.tool, rel_recipe)
    return claims


def record_lock(project: Path) -> tuple[str, list[str]]:
    """Build the lock text for a project, plus anything that needs a human.

    Returns the file content and a list of problems. Existing `human-import`
    entries are kept as they are: the user declared those, and nothing here is
    entitled to rewrite or invent them.
    """
    claims = claimed_outputs(project)
    files = sorted(asset_files(project))
    problems: list[str] = []

    lines = [
        "# Generated by `joinery lock`. Every asset under art/ and audio/ needs",
        "# an entry: a tool that made it and a recipe that remakes it, or an",
        "# import the user declared. Hashes are measured, never written by hand.",
        "version = 1",
    ]
    for rel in files:
        claim = claims.get(rel)
        if claim is None:
            problems.append(
                f"{rel}: no recipe produces this file, so its origin cannot be "
                "derived. Add a recipe, or declare it as a human import."
            )
            continue
        tool, recipe = claim
        lines += [
            "",
            "[[asset]]",
            f'path = "{rel}"',
            f'sha256 = "{_sha256(project / rel)}"',
            'origin = "tool-created"',
            f'tool = "{tool}"',
            f'recipe = "{recipe}"',
        ]
    unmade = sorted(set(claims) - set(files))
    problems += [f"{rel}: a recipe claims this output but it is not on disk" for rel in unmade]
    return "\n".join(lines) + "\n", problems


def write_lock(project: Path) -> list[str]:
    text, problems = record_lock(project)
    if not problems:
        (project / LOCK_NAME).write_text(text)
    return problems
