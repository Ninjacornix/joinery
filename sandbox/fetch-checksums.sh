#!/usr/bin/env bash
# Record the sha256 of every pinned download, so the image build can verify
# them. Run this on the host, once per version change; it needs network, and the
# build then needs no trust in the URLs.
#
#   sandbox/fetch-checksums.sh            # record every artifact
#   sandbox/fetch-checksums.sh blender    # just one, keeping the others
#
# A URL that does not resolve is a hard failure, so a wrong version in
# versions.env is caught here instead of being baked into an image. Checksums
# are never invented: each one comes from the bytes actually downloaded.
#
# Written for bash 3.2, which is what macOS ships, so no associative arrays.
set -euo pipefail

here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=/dev/null
source "${here}/versions.env"

out=${here}/checksums.txt
want=${1:-all}
tmp=$(mktemp -d)
trap 'rm -rf "${tmp}"' EXIT

mm_under=$(printf '%s' "${MATERIALMAKER_VERSION}" | tr '.' '_')
godot_name="Godot_v${GODOT_VERSION}-${GODOT_CHANNEL}_linux.x86_64"
# Must match audacity.Dockerfile's download location.
debian_audacity="https://deb.debian.org/debian/pool/main/a/audacity"

# One "name url" pair per line. Keep names in step with the Dockerfile.
# MPFB2 publishes no release assets, so its tagged source archive is used;
# the Godot MCP is pinned to a commit, so its commit archive is used.
artifacts="\
godot https://github.com/godotengine/godot/releases/download/${GODOT_VERSION}-${GODOT_CHANNEL}/${godot_name}.zip
blender https://download.blender.org/release/Blender${BLENDER_SERIES}/blender-${BLENDER_VERSION}-linux-x64.tar.xz
mpfb2 https://github.com/makehumancommunity/mpfb2/archive/refs/tags/v${MPFB2_VERSION}.tar.gz
materialmaker https://github.com/RodZill4/material-maker/releases/download/${MATERIALMAKER_VERSION}/material_maker_${mm_under}_linux.tar.gz
surge https://github.com/surge-synthesizer/releases-xt/releases/download/${SURGE_VERSION}/surge-xt-linux-x64-${SURGE_VERSION}.deb
audacity ${debian_audacity}/audacity_${AUDACITY_DEB_VERSION}_amd64.deb
audacitydata ${debian_audacity}/audacity-data_${AUDACITY_DEB_VERSION}_all.deb
godotmcp https://github.com/tugcantopaloglu/godot-mcp/archive/${GODOT_MCP_REF}.tar.gz"

# Start from the existing hashes so fetching one artifact keeps the rest.
kept=${tmp}/kept
: >"${kept}"
if [ -s "${out}" ]; then
  grep -v '^#' "${out}" >"${kept}" || true
fi

failed=0
fetched=${tmp}/fetched
: >"${fetched}"

while read -r name url; do
  [ -n "${name}" ] || continue
  if [ "${want}" != "all" ] && [ "${want}" != "${name}" ]; then
    continue
  fi
  echo "fetching ${name}"
  echo "  <- ${url}"
  if ! curl -fsSL --retry 2 -o "${tmp}/${name}.bin" "${url}"; then
    echo "  FAILED: did not resolve. Check ${name}'s version in versions.env." >&2
    failed=1
    continue
  fi
  hash=$(shasum -a 256 "${tmp}/${name}.bin" | cut -d' ' -f1)
  echo "  ${hash}"
  printf '%s %s\n' "${name}" "${hash}" >>"${fetched}"
done <<EOF
${artifacts}
EOF

{
  echo "# sha256 of each pinned download. Generated by fetch-checksums.sh."
  echo "# Do not edit by hand: a hash here must come from the real artifact."
  # Keep headers outside the sort pipeline. head can buffer past its last
  # requested line and silently consume the artifact hashes from a pipe.
  {
    cat "${fetched}"
    while read -r name hash; do
      [ -n "${name}" ] || continue
      grep -q "^${name} " "${fetched}" || printf '%s %s\n' "${name}" "${hash}"
    done <"${kept}"
  } | sort
} >"${tmp}/out"
mv "${tmp}/out" "${out}"

echo "wrote ${out}"
if [ "${failed}" -ne 0 ]; then
  echo "one or more downloads failed; checksums.txt is incomplete." >&2
  exit 1
fi
